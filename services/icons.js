export function icon(name, size = 18) {
  const definition = icons[name];
  if (!definition) return '';
  return createElement(definition, {
    width: size,
    height: size,
    strokeWidth: 1.8,
    class: 'ui-icon',
    'aria-hidden': 'true',
    focusable: 'false',
  }).outerHTML;
}
